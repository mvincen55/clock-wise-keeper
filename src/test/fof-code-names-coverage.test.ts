import { describe, expect, it } from 'vitest';
import { friendlyCdtName } from '@/lib/fof/cdt-names';
import { safeProcedureLabel } from '@/lib/fof/ai';

describe('patient-friendly names cover the codes the office bills', () => {
  it.each([
    ['D4249', 'Crown Lengthening'], ['D9120', 'Bridge Sectioning'], ['D2954', 'Post and Core'], ['D2740', 'Porcelain Crown'],
    ['D7140', 'Tooth Extraction'], ['D5750', 'Denture Reline (Upper, Lab)'], ['D4212', 'Gum Surgery for a Filling'],
  ])('%s reads as %s', (code, name) => {
    expect(friendlyCdtName(code)).toBe(name);
    expect(safeProcedureLabel(code)).toBe(name);
  });
  it('office variants of a CDT code read as the base procedure', () => {
    expect(friendlyCdtName('D2740C')).toBe('Porcelain Crown');
    expect(friendlyCdtName('D9215A')).toBe('Local Anesthetic');
    expect(friendlyCdtName('d2752.')).toBe(friendlyCdtName('D2752'));
    expect(friendlyCdtName('D4341B')).toBe('Deep Cleaning (Per Quadrant)');
  });
  it('unambiguous office shorthand reads plainly; unknown shorthand stays unnamed', () => {
    expect(friendlyCdtName('2014')).toBe('Preliminary Impression');
    expect(friendlyCdtName('5008')).toBe('Denture Delivery');
    expect(friendlyCdtName('6059D')).toBe('Implant Crown Delivery');
    expect(friendlyCdtName('9434')).toBeNull();
    expect(friendlyCdtName('9100')).toBeNull();
  });
  it('every CDT range the office bills has a name', () => {
    const missing: string[] = [];
    for (const code of OFFICE_CDT_CODES) if (!friendlyCdtName(code)) missing.push(code);
    expect(missing).toEqual([]);
  });
});

